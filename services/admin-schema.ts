import { z } from "zod";
const uuid = z.string().uuid(),
  url = z
    .string()
    .url()
    .refine((v) => v.startsWith("https://"));
const nullableText = z.string().max(5000).nullable().optional();
const institutionURL = z.string().url().refine(v => /^https?:\/\//.test(v));
const localAsset = z.string().regex(/^\/(?:logos|images)\/[a-zA-Z0-9/_\-.]+$/).refine(v => !v.includes('..'));
const evidenceFields = {
  evidence: z.record(z.unknown()).refine(v => JSON.stringify(v).length <= 16000, "Evidence is too large").optional(),
  id: uuid.optional(),
  university_id: uuid,
  source_id: uuid,
  source_url: url,
  year: z.coerce.number().int().min(1900).max(2100).nullable().optional(),
  notes: nullableText,
};
const optionalUUID = uuid.nullable().optional();
const areas = z.preprocess(
  (v) =>
    typeof v === "string"
      ? v
          .split(",")
          .map((s) => s.trim())
          .filter(Boolean)
      : v,
  z.array(z.string().max(100)).max(20).default([]),
);
export const entitySchemas = {
  departments: z.object({
    ...evidenceFields,
    name: z.string().min(2).max(200),
    official_url: url,
  }),
  professors: z.object({
    ...evidenceFields,
    name: z.string().min(2).max(200),
    title: nullableText,
    department_id: optionalUUID,
    research_areas: areas,
    profile_url: url,
    biography: nullableText,
  }),
  research: z.object({
    ...evidenceFields,
    title: z.string().min(2).max(300),
    department_id: optionalUUID,
    research_areas: areas,
    summary: nullableText,
    official_url: url,
  }),
  deadlines: z.object({
    ...evidenceFields,
    title: z.string().min(2).max(200),
    program_id: optionalUUID,
    student_category: z.string().min(1),
    cycle: z.string().min(1),
    due_at: z.string().datetime({ offset: true }).nullable().optional(),
    due_date: z.string().date().nullable().optional(),
    timezone: z.string().min(1),
    application_url: url,
  }).refine(r => !!r.due_at !== !!r.due_date, { message: "Enter either a precise timestamp or a date-only deadline, not both." }),
  requirements: z.object({
    ...evidenceFields,
    program_id: optionalUUID,
    kind: z.enum(["SAT", "ACT", "IELTS", "TOEFL", "document", "other"]),
    label: z.string().min(1),
    minimum: z.number().nonnegative().nullable().optional(),
    maximum: z.number().nonnegative().nullable().optional(),
    student_category: z.string().min(1),
    required: z.boolean().nullable().optional(),
  }),
  financial_aid: z.object({
    ...evidenceFields,
    name: z.string().min(2),
    student_category: z.string().min(1),
    eligibility: z.string().min(1).max(5000),
    application_url: url,
    amount: z.number().nonnegative().nullable().optional(),
    currency: z
      .string()
      .regex(/^[A-Z]{3}$/)
      .nullable()
      .optional(),
  }),
  media: z.object({
    ...evidenceFields,
    kind: z.enum(["campus", "logo", "faculty"]),
    professor_id: optionalUUID,
    url: z.union([url, localAsset]),
    alt: z.string().min(1),
    creator: z.string().min(1),
    license: z.string().min(1),
    license_url: url,
    reuse_permitted: z.boolean().default(false),
    width: z.number().int().positive().nullable().optional(),
    height: z.number().int().positive().nullable().optional(),
  }),
  ingestion_feeds: z.object({
    id: uuid.optional(),
    source_id: uuid,
    name: z.string().min(2),
    adapter: z.enum(["collegestat-json", "scorecard"]),
    url,
    enabled: z.boolean().default(false),
    interval_hours: z.number().int().min(1).max(8760).default(168),
  }),
  external_identifiers: z.object({
    id: uuid.optional(),
    university_id: uuid,
    system: z.enum(["ipeds", "ror", "wikidata"]),
    external_id: z.string().min(1).max(100),
  }),
  universities: z.object({
    id: uuid.optional(),
    name: z.string().min(2).max(200),
    slug: z.string().regex(/^[a-z0-9-]+$/),
    short_name: nullableText,
    country_code: z.string().regex(/^[A-Z]{2}$/),
    city: nullableText,
    region: nullableText,
    website: institutionURL.nullable().optional(),
    admissions_url: institutionURL.nullable().optional(),
    financial_aid_url: institutionURL.nullable().optional(),
    description: nullableText,
    published: z.boolean().default(false),
    university_type: nullableText,
    reference_url: url.nullable().optional(),
    logo_url: z.union([url, localAsset]).nullable().optional(),
    logo_source_url: url.nullable().optional(),
    logo_usage_notes: nullableText,
  }),
  data_sources: z.object({
    id: uuid.optional(),
    name: z.string().min(2).max(200),
    organization: nullableText,
    url,
    source_type: z.enum([
      "official",
      "government",
      "accreditation",
      "ranking",
      "secondary",
      "scholarship",
    ]),
    license_notes: nullableText,
    retrieved_at: z.string().datetime().nullable().optional(),
    trust_level: z.enum(["high", "medium", "low"]).default("medium"),
  }),
  programs: z.object({
    id: uuid.optional(),
    name: z.string().min(2),
    subject: z.string().min(2),
    degree_level: z.string().min(2),
    language: nullableText,
  }),
  university_programs: z.object({
    source_id: uuid,
    source_url: url,
    id: uuid.optional(),
    university_id: uuid,
    program_id: uuid,
  }),
  university_scholarships: z.object({
    id: uuid.optional(),
    university_id: uuid,
    scholarship_id: uuid,
  }),
  ranking_providers: z.object({
    id: uuid.optional(),
    name: z.string().min(2),
    slug: z.string().regex(/^[a-z0-9-]+$/),
    website: url,
    license_status: z.enum(["permitted", "unavailable", "restricted"]),
    methodology: nullableText,
  }),
  ranking_editions: z.object({
    id: uuid.optional(),
    provider_id: uuid,
    year: z.coerce.number().int().min(1900).max(2100),
    subject: z.string().min(1),
    region: z.string().min(1),
    permitted: z.boolean().default(false),
  }),
  ranking_entries: z.object({
    id: uuid.optional(),
    university_id: uuid,
    edition_id: uuid,
    rank: z.coerce.number().int().positive(),
    year: z.coerce.number().int().min(1900).max(2100),
    source_id: uuid,
    notes: nullableText,
  }),
  scholarships: z.object({
    id: uuid.optional(),
    name: z.string().min(2),
    slug: z.string().regex(/^[a-z0-9-]+$/),
    description: nullableText,
    provider: nullableText,
    country_code: z.string().max(2).nullable().optional(),
    level: z.string().min(1),
    funding_type: z.enum(["full", "partial", "variable"]),
    amount: z.number().nonnegative().nullable().optional(),
    currency: z.string().regex(/^[A-Z]{3}$/),
    deadline: z
      .string()
      .regex(/^\d{4}-\d{2}-\d{2}$/)
      .nullable()
      .optional(),
    application_url: url,
    source_id: uuid,
    published: z.boolean().default(false),
  }),
};
